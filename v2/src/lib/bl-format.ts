/**
 * เลข BL มีวงเล็บที่มีเลขอยู่ข้างใน เช่น "KNT2600123 (MEDU1234567)"
 *
 * สายที่ออกเลข BL ตัวจริงหลังเรือเข้า (KNOT GLOBAL, M+R FORWARDING, AOT ...) ต้องเขียนเลขจริง
 * ไว้ในวงเล็บต่อท้ายก่อนส่ง Partner เพราะ Partner ใช้เลขในวงเล็บไปแลก DO กับสายเรือ
 * วงเล็บเปล่า "( )" ไม่นับ
 */
export function hasBlBrackets(blNo: string | null | undefined): boolean {
  return /\([^()]*[^\s()][^()]*\)/.test(String(blNo ?? ''));
}
